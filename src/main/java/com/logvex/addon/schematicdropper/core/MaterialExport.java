package com.logvex.addon.schematicdropper.core;

import java.util.ArrayList;
import java.util.List;
import java.util.Locale;

/**
 * Renders material sets as plain text for export.
 *
 * <p>Export is a pure string transform so it is fully unit testable and never touches the disk;
 * the caller decides where the text is written.
 */
public final class MaterialExport {
    private MaterialExport() {
    }

    /** Which materials to include. */
    public enum Scope {
        REQUIRED,
        REMAINING,
        COMPLETED,
        MISSING,
        INVALID;

        @Override
        public String toString() {
            return switch (this) {
                case REQUIRED -> "Required";
                case REMAINING -> "Remaining";
                case COMPLETED -> "Completed";
                case MISSING -> "Missing";
                case INVALID -> "Invalid";
            };
        }
    }

    /** A header line plus one {@code id quantity} line per entry, preserving order. */
    public static String render(Scope scope, List<Requirement> requirements, List<MaterialValidator.Issue> invalid) {
        StringBuilder sb = new StringBuilder();
        sb.append("# ").append(title(scope)).append('\n');
        sb.append("# Generated by Log Client SchematicDropper\n");

        if (scope == Scope.INVALID) {
            if (invalid == null || invalid.isEmpty()) {
                sb.append("# No invalid entries.\n");
                return sb.toString();
            }
            for (MaterialValidator.Issue issue : invalid) {
                sb.append("# line ").append(issue.lineNumber()).append(": ")
                    .append(issue.reason()).append(" | ").append(issue.entry()).append('\n');
            }
            return sb.toString();
        }

        long total = 0;
        if (requirements != null) {
            for (Requirement r : requirements) {
                if (r == null || r.required() <= 0) continue;
                sb.append(r.itemId()).append(' ').append(r.required()).append('\n');
                total += r.required();
            }
        }
        sb.append("# total ").append(total).append(" items\n");
        return sb.toString();
    }

    /** Derives the export set for a scope from a tracker snapshot. */
    public static List<Requirement> select(Scope scope, ProgressTracker tracker) {
        List<Requirement> out = new ArrayList<>();
        if (tracker == null) return out;
        for (Requirement r : tracker.plan().requirements()) {
            int confirmed = tracker.confirmed(r.itemId());
            int remaining = Math.max(0, r.required() - confirmed);
            switch (scope) {
                case REQUIRED -> out.add(r);
                case REMAINING -> {
                    if (remaining > 0) out.add(new Requirement(r.itemId(), r.displayName(), remaining));
                }
                case COMPLETED -> {
                    if (confirmed > 0) out.add(new Requirement(r.itemId(), r.displayName(), confirmed));
                }
                case MISSING -> {
                    int missing = tracker.missingQuantity(r.itemId());
                    if (missing > 0) out.add(new Requirement(r.itemId(), r.displayName(), missing));
                }
                case INVALID -> { /* handled separately */ }
            }
        }
        return out;
    }

    private static String title(Scope scope) {
        return switch (scope) {
            case REQUIRED -> "Required materials";
            case REMAINING -> "Remaining materials";
            case COMPLETED -> "Completed materials";
            case MISSING -> "Missing materials";
            case INVALID -> "Invalid entries";
        };
    }

    /** Suggested file name for an export. */
    public static String suggestedFileName(Scope scope) {
        return "log-addon-" + scope.name().toLowerCase(Locale.ROOT) + "-materials.txt";
    }
}
